using CopyPreflight.Core;

namespace CopyPreflight.App;

/// <summary>
/// One finding, shaped for display.
/// </summary>
/// <remarks>
/// <para>
/// A row carries the finding's own text unchanged and adds nothing to it. It never re-grades a
/// severity, never merges two findings that share a path, and never drops one: every finding the rule
/// layer produced has exactly one row, and the row shows the code as well as the wording so that the
/// rule behind it is identifiable.
/// </para>
/// <para>
/// A finding that belongs to no single source object — a target-wide or scan-wide conclusion — is
/// labelled as such. Inventing a path for it, or leaving the column blank so that it reads like a
/// missing value, would both misrepresent it.
/// </para>
/// </remarks>
public sealed record FindingRow
{
    private FindingRow(
        Severity severity,
        string code,
        string title,
        string? sourceRelativePath,
        string explanation,
        string impact,
        string recommendation)
    {
        Severity = severity;
        SeverityLabel = PreflightText.DescribeSeverity(severity);
        Code = code;
        Title = title;
        SourceRelativePath = sourceRelativePath;
        SourcePathText = sourceRelativePath ?? PreflightText.TargetWide;
        Explanation = explanation;
        Impact = impact;
        Recommendation = recommendation;
    }

    /// <summary>How certain the verdict is and what kind of impact it has.</summary>
    public Severity Severity { get; }

    /// <summary>The severity as it is displayed, for sorting and for the list's own labels.</summary>
    public string SeverityLabel { get; }

    /// <summary>Stable identity of the rule that produced the finding.</summary>
    public string Code { get; }

    /// <summary>Short title of the problem.</summary>
    public string Title { get; }

    /// <summary>
    /// The source entry this finding applies to, or <see langword="null"/> for a target-wide or
    /// scan-wide conclusion.
    /// </summary>
    public string? SourceRelativePath { get; }

    /// <summary>The path as it is displayed, which says so explicitly when there is no single path.</summary>
    public string SourcePathText { get; }

    /// <summary>What the problem is and why it applies.</summary>
    public string Explanation { get; }

    /// <summary>What the migration consequence would be.</summary>
    public string Impact { get; }

    /// <summary>Textual advice, generated by a deterministic rule.</summary>
    public string Recommendation { get; }

    /// <summary>
    /// Shapes a finding list for display without changing it: every finding gets one row, and the rows
    /// are ordered blocking first, then warnings, then informational conclusions.
    /// </summary>
    /// <param name="findings">The findings the rule layer produced, in the order the rules ran.</param>
    /// <returns>
    /// One row per finding. Within one severity the rules' own order is kept, so the display is stable
    /// from run to run for the same facts.
    /// </returns>
    /// <exception cref="ArgumentNullException"><paramref name="findings"/> is <see langword="null"/>.</exception>
    internal static IReadOnlyList<FindingRow> FromFindings(IReadOnlyList<Finding> findings)
    {
        ArgumentNullException.ThrowIfNull(findings);

        return
        [
            .. findings
                .Select((finding, index) => (finding, index))
                .OrderBy(item => PreflightText.SeverityRank(item.finding.Severity))
                .ThenBy(item => item.index)
                .Select(item => new FindingRow(
                    item.finding.Severity,
                    item.finding.Code.Value,
                    item.finding.Title,
                    item.finding.SourceRelativePath,
                    item.finding.Explanation,
                    item.finding.Impact,
                    item.finding.Recommendation)),
        ];
    }
}
