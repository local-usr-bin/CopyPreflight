namespace CopyPreflight.Core;

/// <summary>
/// A single, explainable conclusion produced by the rule layer.
/// </summary>
/// <remarks>
/// <para>
/// A finding is purely descriptive: it states what the problem is, how certain that verdict is,
/// why it applies, what the impact would be and what is recommended. It never triggers a change
/// and it performs no I/O of its own.
/// </para>
/// <para>
/// All texts are currently final, rule-generated strings. There is intentionally no localization
/// layer and no reference to any UI type at this stage.
/// </para>
/// <para>
/// <see cref="SourceRelativePath"/> may be <see langword="null"/>, because findings that are
/// target-wide or scan-wide belong to no single source entry.
/// </para>
/// </remarks>
public sealed record Finding
{
    /// <summary>Creates a finding from its final, rule-generated content.</summary>
    /// <param name="code">Stable identity of the rule that produced this finding.</param>
    /// <param name="severity">How certain the verdict is and what kind of impact it has.</param>
    /// <param name="title">Short title of the problem.</param>
    /// <param name="explanation">What the problem is and why it applies.</param>
    /// <param name="impact">What the migration consequence would be.</param>
    /// <param name="recommendation">Textual advice. Explanatory only; never an automated action.</param>
    /// <param name="sourceRelativePath">
    /// The source entry this finding applies to, expressed as a path relative to the source root.
    /// <see langword="null"/> for target-wide or scan-wide findings.
    /// </param>
    /// <exception cref="ArgumentNullException"><paramref name="code"/> is <see langword="null"/>.</exception>
    /// <exception cref="ArgumentException">
    /// <paramref name="title"/>, <paramref name="explanation"/>, <paramref name="impact"/>,
    /// <paramref name="recommendation"/> or a supplied <paramref name="sourceRelativePath"/> is
    /// null, empty or whitespace.
    /// </exception>
    public Finding(
        FindingCode code,
        Severity severity,
        string title,
        string explanation,
        string impact,
        string recommendation,
        string? sourceRelativePath = null)
    {
        ArgumentNullException.ThrowIfNull(code);

        Code = code;
        Severity = severity;
        Title = RequireText(title, nameof(title));
        Explanation = RequireText(explanation, nameof(explanation));
        Impact = RequireText(impact, nameof(impact));
        Recommendation = RequireText(recommendation, nameof(recommendation));
        SourceRelativePath = sourceRelativePath is null
            ? null
            : RequireText(sourceRelativePath, nameof(sourceRelativePath));
    }

    /// <summary>Stable identity of the rule that produced this finding.</summary>
    public FindingCode Code { get; }

    /// <summary>How certain the verdict is and what kind of impact it has.</summary>
    public Severity Severity { get; }

    /// <summary>Short title of the problem.</summary>
    public string Title { get; }

    /// <summary>What the problem is and why it applies.</summary>
    public string Explanation { get; }

    /// <summary>What the migration consequence would be.</summary>
    public string Impact { get; }

    /// <summary>Textual advice, generated by a deterministic rule.</summary>
    public string Recommendation { get; }

    /// <summary>
    /// Source entry this finding applies to, relative to the source root; or <see langword="null"/>
    /// when the finding applies to the whole target or the whole scan.
    /// </summary>
    public string? SourceRelativePath { get; }

    private static string RequireText(string value, string parameterName)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            throw new ArgumentException(
                "Finding text must not be null, empty or whitespace.",
                parameterName);
        }

        return value;
    }
}
